const BASE_FACILITIES = ['냉난방', '와이파이'];

export function buildDetail(space, branch) {
  const primary = space.concepts.map((id) => CONCEPT_COPY[id]).find(Boolean) ?? FALLBACK_COPY;
  const facilities = [...new Set([...space.amenities, ...BASE_FACILITIES])];

  const open = branch?.openHour ?? 7;
  const close = branch?.closeHour ?? 24;

  return {
    headline: primary.headline,
    intro: [space.description, ...primary.intro],
    facilities,
    notes: [...primary.notes, ...COMMON_NOTES],
    hours: `${String(open).padStart(2, '0')}:00 ~ ${close === 24 ? '24:00' : `${String(close).padStart(2, '0')}:00`}`,
  };
}
